namespace Andalos.API.Enums
{
    /// <summary>
    /// 👈 نوع فوترة الصيانة (من يتحمل التكلفة؟)
    /// </summary>
    public enum MaintenanceBillingType
    {
        None = 1,       // على الإدارة (بدون تحميل على المستأجر)
        Offer = 2,      // عرض على المستأجر — له الحرف في القبول أو الرفض
        Mandatory = 3   // إجبارية — تحميل مباشر بدون موافقة (مثل أضرار المستأجر أو ما تقتضيه العقد)
    }

    /// <summary>
    /// 👈 حالة تحميل المستأجر (دورة حياة العرض المالي)
    /// </summary>
    public enum ChargeStatus
    {
        PendingApproval = 1, // عرض مقدم — بانتظار موافقة المستأجر (لا يدخل المديونية)
        Approved = 2,        // مؤكد — وافق المستأجر (أو إجبارية) ويدخل المديونية
        Rejected = 3,        // مرفوض من المستأجر (لا يدخل المديونية)
        Paid = 4             // مسدد بالكامل
    }
}
